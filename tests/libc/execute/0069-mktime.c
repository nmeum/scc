#ifndef __unix__
#define putenv(x) (x)
/*
 * Ok, this is by definition undefined behaviour because
 * we are using the name of a library function. The reallity
 * is that if you use a static linker then this would
 * overload the libc getenv and it will work as expected,
 * but if you use a dynamic linker then the internal
 * references will be tied to the internal getenv function
 * and this would not work. For our main use case that is
 * testing scc libc this is good enough, and with the
 * fallback to putenv this will work in the systems we are
 * interested on
 */
char *
getenv(const char *name)
{
	if (strcmp(name, "TZ") != 0)
		return NULL;
	return "UTC";
}
#endif

int
main(void)
{
	time_t t;
	char buf[70];
	struct tm *tm;
	struct test *tp;

	puts("testing");
	putenv("TZ=UTC");
	for (tp = tests; tp < &tests[NELEM(tests)]; ++tp) {
		printf("test %d\n", (int) (tp - tests));
		t = mktime(&tp->tm);
		if (tp->fail) {
			printf("tm_wday=%d, tm_yday=%d\n",
			       tp->tm.tm_wday, tp->tm.tm_yday);
			puts(t == -1 ? "failed" : "not failed");
			continue;
		}
		printf("tm_sec=%2d, "
		       "tm_min=%2d, "
		       "tm_hour=%2d, "
		       "tm_mday=%2d, "
		       "tm_mon=%2d, "
		       "tm_year=%4d, "
		       "tm_wday=%d, "
		       "tm_yday=%3d, "
		       "tm_isdst=%d\n",
		       tp->tm.tm_sec,
		       tp->tm.tm_min,
		       tp->tm.tm_hour,
		       tp->tm.tm_mday,
		       tp->tm.tm_mon,
		       tp->tm.tm_year,
		       tp->tm.tm_wday,
		       tp->tm.tm_yday,
		       tp->tm.tm_isdst);
		strftime(buf, sizeof(buf), "%c %Z", &tp->tm);
		puts(buf);

		tm = gmtime(&t);
		strftime(buf, sizeof(buf), "%c %Z", tm);
		puts(buf);

		tm = localtime(&t);
		strftime(buf, sizeof(buf), "%c %Z", tm);
		puts(buf);

		fputs(asctime(tm), stdout);
		fputs(ctime(&t), stdout);
	}
	puts("done");

	return 0;
}

